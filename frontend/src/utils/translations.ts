export const useTranslation = (lang: Language | string = 'en') => {
  const selected = (typeof lang === 'string' && TRANSLATIONS[lang as Language]) ? (lang as Language) : 'en';
  const dict = TRANSLATIONS[selected] || TRANSLATIONS.en;

  const t = (key: string, fallback?: string): string => {
    return dict[key] || TRANSLATIONS.en[key] || fallback || key;
  };

  return { t, lang: selected };
};
